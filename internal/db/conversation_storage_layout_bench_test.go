// This is a synthetic layout experiment, not an application migration. Each
// layout has its own temporary archive; only bench_* objects receive data.
const layoutColumns = "session_id,message_id,ordinal,role,timestamp,source_id,body,digest,text_bytes,visible_digest,visible_text_bytes,visible_gap,gap,deleted,removed,revision"
const layoutSessionColumns = "session_id,revision,deleted,gap"

type conversationLayout struct {
	db       *DB
	physical string
	refs     bool
}

func newConversationLayout(ctx context.Context, tb testing.TB, refs bool) conversationLayout {
	tb.Helper()
	l := conversationLayout{db: testDB(tb), physical: "bench_messages", refs: refs}
	if refs {
		l.physical = "bench_ref_messages"
	}
	require.NoError(tb, l.db.Update(ctx, func(tx *sql.Tx) error {
		if _, err := tx.ExecContext(ctx, `CREATE TABLE bench_metadata(key TEXT PRIMARY KEY,value TEXT NOT NULL)`); err != nil {
			return err
		}
		if refs {
			if _, err := tx.ExecContext(ctx, `CREATE TABLE bench_sessions(ref INTEGER PRIMARY KEY,session_id TEXT NOT NULL UNIQUE)`); err != nil {
				return err
			}
		}
		rows, err := tx.QueryContext(ctx, `SELECT sql FROM sqlite_master WHERE tbl_name IN ('conversation_messages','conversation_session_changes') AND type IN ('table','index') AND sql IS NOT NULL ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END,name`)
		if err != nil {
			return err
		}
		var statements []string
		for rows.Next() {
			var ddl string
			if err := rows.Scan(&ddl); err != nil {
				_ = rows.Close()
				return err
			}
			ddl = strings.ReplaceAll(ddl, "conversation_messages", l.physical)
			messageDDL := strings.Contains(ddl, l.physical)
			ddl = strings.ReplaceAll(ddl, "conversation_session_changes", "bench_session_changes")
			if refs && messageDDL {
				ddl = strings.ReplaceAll(ddl, "session_id", "session_ref")
				ddl = strings.ReplaceAll(ddl, "session_ref TEXT NOT NULL", "session_ref INTEGER NOT NULL REFERENCES bench_sessions(ref)")
			}
			statements = append(statements, ddl)
		}
		if err := rows.Err(); err != nil {
			_ = rows.Close()
			return err
		}
		if err := rows.Close(); err != nil {
			return err
		}
		for _, ddl := range statements {
			if _, err := tx.ExecContext(ctx, ddl); err != nil {
				return err
			}
		}
		if refs {
			_, err = tx.ExecContext(ctx, `CREATE VIEW bench_messages AS SELECT r.session_id,m.`+strings.ReplaceAll(strings.TrimPrefix(layoutColumns, "session_id,"), ",", ",m.")+` FROM bench_ref_messages m JOIN bench_sessions r ON r.ref=m.session_ref`)
		}
		return err
	}))
	return l
}

// Copy in bounded transactions, resolving references by their exact text key.
// Only positive rowids generated by the fixtures are supported. The source
// is attached read-only. Install triggers afterward so existing revisions do
// not publish changes. This helper is not a resumable production migration.
func copyConversationLayout(ctx context.Context, source *DB, dest conversationLayout) error {
	conn, err := dest.db.getWriter().Conn(ctx)
	if err != nil {
		return err
	}
	defer conn.Close()
	if _, err := conn.ExecContext(ctx, "ATTACH DATABASE ? AS bench_source", layoutReadOnlyURI(source)); err != nil {
		return err
	}
	defer func() { _, _ = conn.ExecContext(context.WithoutCancel(ctx), "DETACH DATABASE bench_source") }()
	for _, table := range []struct{ source, dest, columns string }{
		{"bench_messages", "bench_ref_messages", layoutColumns},
		{"bench_session_changes", "bench_session_changes", layoutSessionColumns},
	} {
		var after int64
		for {
			tx, err := conn.BeginTx(ctx, nil)
			if err != nil {
				return err
			}
			var through sql.NullInt64
			err = tx.QueryRowContext(ctx, `SELECT MAX(rowid) FROM (SELECT rowid FROM bench_source.`+table.source+` WHERE rowid>? ORDER BY rowid LIMIT 256)`, after).Scan(&through)
			if err == nil && through.Valid {
				if table.source == "bench_messages" {
					_, err = tx.ExecContext(ctx, `INSERT OR IGNORE INTO bench_sessions(session_id) SELECT session_id FROM bench_source.bench_messages WHERE rowid>? AND rowid<=? ORDER BY rowid`, after, through.Int64)
					if err == nil {
						_, err = tx.ExecContext(ctx, `INSERT INTO `+table.dest+` (`+strings.Replace(table.columns, "session_id", "session_ref", 1)+`) SELECT r.ref,s.`+strings.ReplaceAll(strings.TrimPrefix(table.columns, "session_id,"), ",", ",s.")+` FROM bench_source.`+table.source+` s JOIN bench_sessions r ON r.session_id=s.session_id WHERE s.rowid>? AND s.rowid<=? ORDER BY s.rowid`, after, through.Int64)
					}
				} else {
					_, err = tx.ExecContext(ctx, `INSERT INTO `+table.dest+` SELECT `+table.columns+` FROM bench_source.`+table.source+` WHERE rowid>? AND rowid<=? ORDER BY rowid`, after, through.Int64)
				}
			}
			if err != nil {
				_ = tx.Rollback()
				return err
			}
			if err := tx.Commit(); err != nil {
				return err
			}
			if !through.Valid {
				break
			}
			after = through.Int64
		}
	}
	_, err = conn.ExecContext(ctx, `INSERT INTO bench_metadata SELECT * FROM bench_source.bench_metadata`)
	return err
}

func layoutReadOnlyURI(d *DB) string {
	return (&url.URL{Scheme: "file", Path: d.Path(), RawQuery: "mode=ro"}).String()
}

func installLayoutRevisionTriggers(ctx context.Context, tb testing.TB, l conversationLayout) {
	tb.Helper()
	rows, err := l.db.Reader().Query(ctx, `SELECT name,sql FROM sqlite_master WHERE type='trigger' AND name IN ('conversation_messages_revision','conversation_messages_revise','conversation_visible_revise') ORDER BY name`)
	require.NoError(tb, err)
	var statements []string
	for rows.Next() {
		var name, ddl string
		require.NoError(tb, rows.Scan(&name, &ddl))
		ddl = strings.Replace(ddl, name, "bench_"+name, 1)
		ddl = strings.ReplaceAll(ddl, "conversation_messages", l.physical)
		ddl = strings.ReplaceAll(ddl, "archive_metadata", "bench_metadata")
		if l.refs {
			ddl = strings.ReplaceAll(ddl, "session_id", "session_ref")
		}
		statements = append(statements, ddl)
	}
	require.NoError(tb, rows.Err())
	require.NoError(tb, rows.Close())
	require.Len(tb, statements, 3)
	for _, ddl := range statements {
		_, err := l.db.getWriter().ExecContext(ctx, ddl)
		require.NoError(tb, err)
	}
}

func layoutQuery(ctx context.Context, d *DB, query string, args ...any) ([][]any, error) {
	rows, err := d.Reader().Query(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	columns, err := rows.Columns()
	if err != nil {
		return nil, err
	}
	var result [][]any
	for rows.Next() {
		values, pointers := make([]any, len(columns)), make([]any, len(columns))
		for i := range values {
			pointers[i] = &values[i]
		}
		if err := rows.Scan(pointers...); err != nil {
			return nil, err
		}
		result = append(result, values)
	}
	return result, rows.Err()
}

func assertLayoutCopy(ctx context.Context, tb testing.TB, source, dest *DB, count int) {
	tb.Helper()
	conn, err := dest.getWriter().Conn(ctx)
	require.NoError(tb, err)
	defer conn.Close()
	_, err = conn.ExecContext(ctx, "ATTACH DATABASE ? AS bench_source", layoutReadOnlyURI(source))
	require.NoError(tb, err)
	defer func() {
		_, err := conn.ExecContext(context.WithoutCancel(ctx), "DETACH DATABASE bench_source")
		require.NoError(tb, err)
	}()
	for _, table := range []string{"main.bench_messages", "bench_source.bench_messages"} {
		var got int
		require.NoError(tb, conn.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+table).Scan(&got))
		assert.Equal(tb, count, got)
	}
	for _, table := range []struct{ name, columns string }{{"bench_messages", layoutColumns}, {"bench_session_changes", layoutSessionColumns}} {
		for _, pair := range [][2]string{{"main", "bench_source"}, {"bench_source", "main"}} {
			var different int
			require.NoError(tb, conn.QueryRowContext(ctx, `SELECT COUNT(*) FROM (SELECT `+table.columns+` FROM `+pair[0]+`.`+table.name+` EXCEPT SELECT `+table.columns+` FROM `+pair[1]+`.`+table.name+`)`).Scan(&different))
			assert.Zero(tb, different, "all logical fields must survive the transformation")
		}
	}
	var same bool
	require.NoError(tb, conn.QueryRowContext(ctx, `SELECT (SELECT value FROM main.bench_metadata WHERE key=?) IS (SELECT value FROM bench_source.bench_metadata WHERE key=?)`, conversationRevisionKey, conversationRevisionKey).Scan(&same))
	assert.True(tb, same, "copying does not allocate publication revisions")
}

func TestConversationStorageLayoutCopyPreservesHistory(t *testing.T) {
	ctx := t.Context()
	source, dest := newConversationLayout(ctx, t, false), newConversationLayout(ctx, t, true)
	_, err := source.db.getWriter().ExecContext(ctx, `INSERT INTO bench_messages VALUES
 ('Case','A',0,'assistant','2025-02-03T04:05:06Z','native',NULL,'legacy',57,'visible-legacy',13,'visible-gap','identity_ambiguous',0,0,7);
 INSERT INTO bench_messages(session_id,message_id,ordinal,role,source_id,body,digest,deleted,removed,revision) VALUES
 ('Case','a',1,'user','','','',1,1,11),
 ('case','A',0,'assistant',CAST(x'73006f' AS TEXT),'','digest',0,0,19),
 ('','',0,'user','',NULL,'',1,1,23),
 (CAST(x'4300617365' AS TEXT),CAST(x'6d006964' AS TEXT),9,'assistant','opaque',CAST(x'62006f6479' AS TEXT),'legacy-not-sha',1,0,31),
 ('Case','return',2,'assistant','native-retired',NULL,'kept',1,1,37);
 INSERT INTO bench_session_changes VALUES('session-only',89,1,'archive_content_excluded'),('Case',101,0,'');
 INSERT INTO bench_metadata VALUES('conversation_publication_revision','123')`)
	require.NoError(t, err)
	require.NoError(t, copyConversationLayout(ctx, source.db, dest))
	assertLayoutCopy(ctx, t, source.db, dest.db, 6)
	got, err := layoutQuery(ctx, dest.db, `SELECT `+layoutColumns+` FROM bench_messages ORDER BY revision`)
	require.NoError(t, err)
	assert.Equal(t, [][]any{
		{"Case", "A", int64(0), "assistant", "2025-02-03T04:05:06Z", "native", nil, "legacy", int64(57), "visible-legacy", int64(13), "visible-gap", "identity_ambiguous", int64(0), int64(0), int64(7)},
		{"Case", "a", int64(1), "user", "", "", "", "", int64(0), "", int64(0), "visible_text_unavailable", "", int64(1), int64(1), int64(11)},
		{"case", "A", int64(0), "assistant", "", "s\x00o", "", "digest", int64(0), "", int64(0), "visible_text_unavailable", "", int64(0), int64(0), int64(19)},
		{"", "", int64(0), "user", "", "", nil, "", int64(0), "", int64(0), "visible_text_unavailable", "", int64(1), int64(1), int64(23)},
		{"C\x00ase", "m\x00id", int64(9), "assistant", "", "opaque", "b\x00ody", "legacy-not-sha", int64(0), "", int64(0), "visible_text_unavailable", "", int64(1), int64(0), int64(31)},
		{"Case", "return", int64(2), "assistant", "", "native-retired", nil, "kept", int64(0), "", int64(0), "visible_text_unavailable", "", int64(1), int64(1), int64(37)},
	}, got)
	journal, err := layoutQuery(ctx, dest.db, `SELECT `+layoutSessionColumns+` FROM bench_session_changes ORDER BY revision`)
	require.NoError(t, err)
	assert.Equal(t, [][]any{{"session-only", int64(89), int64(1), "archive_content_excluded"}, {"Case", int64(101), int64(0), ""}}, journal)
	var refs int
	require.NoError(t, dest.db.Reader().QueryRow(ctx, `SELECT COUNT(*) FROM bench_sessions`).Scan(&refs))
	assert.Equal(t, 4, refs, "distinct opaque keys stay distinct and repeated keys share a reference")
	for _, l := range []conversationLayout{source, dest} {
		installLayoutRevisionTriggers(ctx, t, l)
		key, column := any("Case"), "session_id"
		if l.refs {
			var ref int64
			require.NoError(t, l.db.Reader().QueryRow(ctx, `SELECT ref FROM bench_sessions WHERE session_id='Case'`).Scan(&ref))
			key, column = ref, "session_ref"
		}
		_, err := l.db.getWriter().ExecContext(ctx, "UPDATE "+l.physical+" SET digest='changed' WHERE "+column+"=? AND message_id='A'", key)
		require.NoError(t, err)
		_, err = l.db.getWriter().ExecContext(ctx, "UPDATE "+l.physical+" SET digest=digest WHERE "+column+"=? AND message_id='A'", key)
		require.NoError(t, err)
		updated, err := layoutQuery(ctx, l.db, `SELECT revision,digest FROM bench_messages WHERE session_id='Case' AND message_id='A'`)
		require.NoError(t, err)
		assert.Equal(t, [][]any{{int64(124), "changed"}}, updated)
		assert.Equal(t, int64(124), layoutPublication(ctx, t, l.db))
	}
}

func TestConversationStorageLayoutCopiesBeyondFirstBatch(t *testing.T) {
	ctx := t.Context()
	source, dest := newConversationLayout(ctx, t, false), newConversationLayout(ctx, t, true)
	seedConversationLayout(ctx, t, source.db, 600)
	require.NoError(t, copyConversationLayout(ctx, source.db, dest))
	assertLayoutCopy(ctx, t, source.db, dest.db, 600)
	boundary, err := layoutQuery(ctx, dest.db, `SELECT revision FROM bench_messages WHERE revision IN (256,257,600) ORDER BY revision`)
	require.NoError(t, err)
	assert.Equal(t, [][]any{{int64(256)}, {int64(257)}, {int64(600)}}, boundary)
	assert.Equal(t, int64(623), layoutPublication(ctx, t, dest.db))
}

func layoutPublication(ctx context.Context, tb testing.TB, d *DB) int64 {
	tb.Helper()
	var revision int64
	require.NoError(tb, d.Reader().QueryRow(ctx, `SELECT CAST(value AS INTEGER) FROM bench_metadata WHERE key=?`, conversationRevisionKey).Scan(&revision))
	return revision
}

func layoutDatabaseBytes(ctx context.Context, tb testing.TB, d *DB) float64 {
	tb.Helper()
	var pages, size int64
	require.NoError(tb, d.Reader().QueryRow(ctx, "PRAGMA page_count").Scan(&pages))
	require.NoError(tb, d.Reader().QueryRow(ctx, "PRAGMA page_size").Scan(&size))
	return float64(pages * size)
}

func layoutSession(i int) string {
	return fmt.Sprintf("provider:synthetic-session-%08d-0123456789abcdef", i/100)
}

func seedConversationLayout(ctx context.Context, tb testing.TB, d *DB, count int) {
	tb.Helper()
	for start := 0; start < count; start += 1000 {
		require.NoError(tb, d.Update(ctx, func(tx *sql.Tx) error {
			stmt, err := tx.PrepareContext(ctx, "INSERT INTO bench_messages ("+layoutColumns+") VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)")
			if err != nil {
				return err
			}
			defer stmt.Close()
			for i := start; i < min(start+1000, count); i++ {
				removed := i%5 == 0
				_, err := stmt.ExecContext(ctx, layoutSession(i), fmt.Sprintf("%032x", i), i%100, "assistant", "2025-01-01T00:00:00Z", fmt.Sprintf("source-%08d", i), nil, strings.Repeat("a", 64), 1024+i%128, strings.Repeat("b", 64), 500+i%128, "", "", removed || i%17 == 0, removed, i+1)
				if err != nil {
					return err
				}
			}
			return nil
		}))
	}
	_, err := d.getWriter().ExecContext(ctx, `INSERT INTO bench_session_changes SELECT session_id,?+ROW_NUMBER() OVER (ORDER BY session_id),MAX(deleted),'' FROM bench_messages GROUP BY session_id`, count)
	require.NoError(tb, err)
	_, err = d.getWriter().ExecContext(ctx, "INSERT INTO bench_metadata VALUES(?,?)", conversationRevisionKey, strconv.Itoa(count+(count+99)/100+17))
	require.NoError(tb, err)
}

func BenchmarkConversationStorageLayout(b *testing.B) {
	count := 100_000
	if raw := os.Getenv("AGENTSVIEW_BENCH_CONVERSATION_ROWS"); raw != "" {
		var err error
		count, err = strconv.Atoi(raw)
		require.NoError(b, err)
		require.GreaterOrEqual(b, count, 1000)
		require.LessOrEqual(b, count, 2_000_000)
	}
	ctx := b.Context()
	source, candidate := newConversationLayout(ctx, b, false), newConversationLayout(ctx, b, true)
	seedConversationLayout(ctx, b, source.db, count)
	require.NoError(b, copyConversationLayout(ctx, source.db, candidate))
	assertLayoutCopy(ctx, b, source.db, candidate.db, count)
	for _, l := range []conversationLayout{source, candidate} {
		installLayoutRevisionTriggers(ctx, b, l)
		require.NoError(b, l.db.CheckpointWALTruncate(ctx))
		_, err := l.db.getWriter().ExecContext(ctx, "VACUUM; ANALYZE")
		require.NoError(b, err)
		require.NoError(b, l.db.CheckpointWALTruncate(ctx))
	}
	target := count/2 + 1
	through := layoutPublication(ctx, b, source.db)
	cases := []struct {
		name, query string
		args        []any
		wantRows    int
	}{
		{"live_page", "SELECT " + layoutColumns + " FROM bench_messages WHERE session_id=? AND removed=0 AND ordinal>=? ORDER BY ordinal LIMIT 50", []any{layoutSession(target), 20}, 50},
		{"message_id", "SELECT " + layoutColumns + " FROM bench_messages WHERE session_id=? AND message_id=?", []any{layoutSession(target), fmt.Sprintf("%032x", target)}, 1},
		{"source_match", "SELECT COUNT(*),MIN(message_id),MAX(removed) FROM bench_messages WHERE session_id=? AND source_id=?", []any{layoutSession(target), fmt.Sprintf("source-%08d", target)}, 1},
		{"revision_feed", `SELECT 'message',` + conversationChangeColumns + `,revision AS publication_revision FROM bench_messages WHERE revision>? AND revision<=?
 UNION ALL SELECT 'session',session_id,'',CAST(revision AS TEXT),0,'',NULL,deleted,gap,'',0,revision FROM bench_session_changes WHERE revision>? AND revision<=?
 ORDER BY publication_revision LIMIT ?`, []any{count - 50, through, count - 50, through, 100}, min(100, 50+(count+99)/100)},
	}
	for _, tc := range cases {
		before, err := layoutQuery(ctx, source.db, tc.query, tc.args...)
		require.NoError(b, err)
		after, err := layoutQuery(ctx, candidate.db, tc.query, tc.args...)
		require.NoError(b, err)
		require.Len(b, before, tc.wantRows, tc.name)
		require.Equal(b, before, after)
	}
	for _, entry := range []struct {
		name string
		l    conversationLayout
	}{{"text_keys", source}, {"integer_refs", candidate}} {
		l := entry.l
		// Total allocated SQLite main-file pages, including the same empty
		// application archive overhead; not a per-table or reclaimed-byte claim.
		fixtureBytes := layoutDatabaseBytes(ctx, b, l.db)
		b.Run(fmt.Sprintf("rows_%d/%s", count, entry.name), func(b *testing.B) {
			for _, tc := range cases {
				b.Run(tc.name, func(b *testing.B) {
					plan, err := layoutQuery(b.Context(), l.db, "EXPLAIN QUERY PLAN "+tc.query, tc.args...)
					require.NoError(b, err)
					b.Logf("query plan: %v", plan)
					b.ReportAllocs()
					for b.Loop() {
						_, err := layoutQuery(b.Context(), l.db, tc.query, tc.args...)
						require.NoError(b, err)
					}
					b.ReportMetric(fixtureBytes, "fixture-db-bytes")
				})
			}
			// These are physical-row update costs, excluding reference lookup or
			// creation and the application's complete message-write transaction.
			key, column := any(layoutSession(target)), "session_id"
			if l.refs {
				var ref int64
				require.NoError(b, l.db.Reader().QueryRow(b.Context(), "SELECT ref FROM bench_sessions WHERE session_id=?", key).Scan(&ref))
				key, column = ref, "session_ref"
			}
			for _, noop := range []bool{false, true} {
				name := "physical_update"
				if noop {
					name = "physical_noop_update"
				}
				b.Run(name, func(b *testing.B) {
					query := "UPDATE " + l.physical + " SET digest=? WHERE " + column + "=? AND message_id=?"
					digests := [2]string{strings.Repeat("c", 64), strings.Repeat("d", 64)}
					args := []any{digests[1], key, fmt.Sprintf("%032x", target)}
					// Repeated samples share the fixture. Reset before timing so
					// the first measured update always changes a same-size digest.
					_, err := l.db.getWriter().ExecContext(b.Context(), query, args...)
					require.NoError(b, err)
					before := layoutPublication(b.Context(), b, l.db)
					if noop {
						query = "UPDATE " + l.physical + " SET digest=digest WHERE " + column + "=? AND message_id=?"
						args = args[1:]
					}
					iteration := 0
					b.ReportAllocs()
					for b.Loop() {
						if !noop {
							args[0] = digests[iteration%2]
						}
						_, err := l.db.getWriter().ExecContext(b.Context(), query, args...)
						require.NoError(b, err)
						iteration++
					}
					want := before
					if !noop {
						want += int64(iteration)
					}
					assert.Equal(b, want, layoutPublication(b.Context(), b, l.db))
					b.ReportMetric(fixtureBytes, "fixture-db-bytes")
				})
			}
		})
	}
}
